#!/usr/bin/env node
// Copies the Pairwise design system into leadlane.html, between the `pairwise:start` and `pairwise:end` markers:
// the Atkinson Hyperlegible Next faces (embedded, so the app makes no network requests), the tokens, and the
// sections of the Pairwise component CSS that LeadLane uses. LeadLane itself has no build step; run this only
// when you want to pick up a newer Pairwise.
//
//   node scripts/sync-pairwise.mjs <path to a pairwise-saas-design-system checkout>
//
// The checkout needs a package build (`pnpm install && pnpm run ci`) so design-system/components/ holds the fonts.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PW = process.argv[2];
if (!PW) { console.error("usage: node scripts/sync-pairwise.mjs <path to pairwise-saas-design-system>"); process.exit(1); }
const read = (p) => readFileSync(join(PW, p), "utf8");

const version = JSON.parse(read("packages/ui/package.json")).version;

// 1. Fonts: the sans faces from the generated bundle, with each woff2 inlined. Mono is left out: LeadLane shows no
//    identifiers or code, and the token's fallback stack covers it.
const bundle = read("design-system/components/bundle.css");
const faces = [...bundle.matchAll(/@font-face \{[^}]*\}/g)].map((m) => m[0]).filter((f) => f.includes("'Atkinson Hyperlegible Next'"));
if (faces.length === 0) { console.error("no Atkinson Hyperlegible Next faces found in design-system/components/bundle.css"); process.exit(1); }
const fontCss = faces.map((face) => face.replace(/url\(\.\/fonts\/([^)]+\.woff2)\)/, (_m, file) => {
  const b64 = readFileSync(join(PW, "design-system/components/fonts", file)).toString("base64");
  return `url(data:font/woff2;base64,${b64})`;
})).join("\n");
mkdirSync(join(ROOT, "LICENSES"), { recursive: true });
writeFileSync(join(ROOT, "LICENSES", "atkinson-hyperlegible-next-OFL.txt"), read("design-system/components/fonts/atkinson-hyperlegible-next.LICENSE.txt"));

// 2. Tokens, as generated by Pairwise.
const tokens = read("design-system/tokens.css").trim();

// 3. Component CSS. Sections start with a comment line after a blank line; keep the base block plus these.
const KEEP = ["Buttons", "Status", "Fields & popovers", "Crumbs, tabs, page header", "Panels & metrics", "Skeleton & states",
  "Banners & toasts", "Layers", "Table", "Shell", "Form controls", "Toaster", "Tag"];
const lines = read("packages/ui/src/styles.css").split("\n");
const sections = [{ name: "base", lines: [] }];
lines.forEach((line, i) => {
  const heading = i > 0 && lines[i - 1].trim() === "" && line.match(/^\/\* (?:-+ )?(.+?)(?: -+)? \*\/$/);
  if (heading) sections.push({ name: heading[1], lines: [] });
  sections[sections.length - 1].lines.push(line);
});
const pick = (name) => sections.find((s) => s.name === name || s.name.startsWith(name + ":"));
const missing = KEEP.filter((k) => !pick(k));
if (missing.length) { console.error(`sections not found in styles.css: ${missing.join(", ")}`); process.exit(1); }
const components = [sections[0], ...KEEP.map(pick)].map((s) => s.lines.join("\n").trim()).join("\n\n");

const block = [
  "/* pairwise:start */",
  `/* Pairwise design system, @pairwise/ui ${version}: fonts, tokens and component CSS.`,
  "   Copied by scripts/sync-pairwise.mjs from github.com/mithunmanohar/pairwise-saas-design-system. Do not edit by hand.",
  "   Atkinson Hyperlegible Next: SIL Open Font License 1.1, see LICENSES/atkinson-hyperlegible-next-OFL.txt. */",
  fontCss, "", tokens, "", components,
  "/* pairwise:end */",
].join("\n");

const file = join(ROOT, "leadlane.html");
const html = readFileSync(file, "utf8");
const re = /\/\* pairwise:start \*\/[\s\S]*?\/\* pairwise:end \*\//;
if (!re.test(html)) { console.error("leadlane.html has no pairwise:start / pairwise:end markers"); process.exit(1); }
writeFileSync(file, html.replace(re, () => block));
console.log(`leadlane.html: Pairwise ${version} (${faces.length} font faces, ${KEEP.length + 1} CSS sections), ${Math.round(Buffer.byteLength(readFileSync(file)) / 1024)} KB`);
